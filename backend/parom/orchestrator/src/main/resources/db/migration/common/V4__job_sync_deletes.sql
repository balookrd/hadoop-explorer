-- =============================================================================
-- V4: флаг репликации удалений у задания
-- =============================================================================
-- Удаления, увиденные inotify на источнике, переносятся на приемник только если
-- оператор включил это для задания. Колонка добавляется отдельной миграцией,
-- потому что базы, принятые через baseline, V1 не применяли.
--
-- Значение по умолчанию false: удаление данных на приемнике необратимо, и
-- существующие задания не должны начать удалять данные после обновления.
-- =============================================================================

alter table replication_jobs add column if not exists sync_deletes boolean default false not null;
