-- =============================================================================
-- V6: одно событие в DLQ задачи — одна запись
-- =============================================================================
-- Запись в DLQ шла проверкой «есть ли уже» и вставкой без уникального ключа:
-- два отчета одного события, пришедшие на разные узлы оркестратора, давали
-- две записи, и оператор переигрывал событие дважды. Перед индексом дубли
-- схлопываются: остается запись с наименьшим id.
-- =============================================================================

delete from hms_dead_letter_events d
where exists (
    select 1 from hms_dead_letter_events d2
    where d2.hms_job_id = d.hms_job_id
      and d2.event_id = d.event_id
      and d2.id < d.id
);

create unique index if not exists uq_hms_dlq_job_event on hms_dead_letter_events (hms_job_id, event_id);
