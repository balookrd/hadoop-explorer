-- =============================================================================
-- V11 (PostgreSQL): поиск подзадачи данных по пути
-- =============================================================================
-- Агент заводит подзадачу на каждую партицию, и оркестратор сначала ищет уже
-- заведенную с тем же путем. Индекс был только по parent_job_id: у задачи на 200k
-- партиций каждый поиск читал все ее подзадачи, а за bootstrap — квадрат этого числа.
--
-- Hash, а не B-tree: путь до 8192 символов не помещается в строку индекса B-tree
-- (предел около 2,7 КБ), а поиск идет только на равенство.
-- =============================================================================

create index if not exists idx_jobs_source_path_hash on replication_jobs using hash (source_path);
